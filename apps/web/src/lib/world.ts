export type IslandState = "fog" | "explored" | "conquered";

export interface IslandView {
  island: Island;
  title: string;
  lessons: { id: string; title: string; order: number; done: boolean }[];
  done: number;
  state: IslandState;
  /** The lesson to go to next on this island. */
  next?: { id: string; title: string };
}

export function buildWorld(progress: LessonProgress[], beaten: string[]): IslandView[] {
  const prog = new Map(progress.map((p) => [p.lessonId, p]));
  return ISLANDS.filter((i) => openLabs.some((l) => l.id === i.lab)).map((island) => {
    const lessons = lessonsForLab(island.lab).map((e) => ({ id: e.lesson.id, title: e.lesson.title, order: e.lesson.order, done: !!prog.get(e.lesson.id)?.completedAt }));
    const done = lessons.filter((l) => l.done).length;
    const touched = lessons.some((l) => prog.has(l.id));
    const state: IslandState = beaten.includes(island.lab) ? "conquered" : touched ? "explored" : "fog";
    const next = lessons.find((l) => !l.done);
    return { island, title: openLabs.find((l) => l.id === island.lab)!.title, lessons, done, state, next: next && { id: next.id, title: next.title } };
  });
}

/** Where the ship is anchored: the island of the lesson you touched last, else the first island. */
export function shipAt(progress: LessonProgress[]): string {
  const last = [...progress].sort((a, b) => b.updatedAt - a.updatedAt)[0];
  const lab = last && lessonEntries.find((e) => e.lesson.id === last.lessonId)?.labId;
  return lab && ISLANDS.some((i) => i.lab === lab) ? lab : ISLANDS[0]!.lab;
}

/** Sea routes: the ideas that join two islands (the same bridges the sky draws). */
export function seaRoutes(): { idea: string; a: string; b: string }[] {
  const labOf = new Map(lessonEntries.map((e) => [e.lesson.id, e.labId]));
  const seen = new Set<string>();
  const out: { idea: string; a: string; b: string }[] = [];
  for (const br of BRIDGES) {
    const a = labOf.get(br.a);
    const b = labOf.get(br.b);
    if (!a || !b || a === b) continue;
    const key = [a, b].sort().join("~");
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ idea: br.idea, a, b });
  }
  return out;
}

/** One fight: walk the questions until the boss or the learner runs out. */
export interface Fight {
  asked: number;
  hits: number;
  misses: number;
}
export const fightOver = (f: Fight, total: number): "won" | "lost" | undefined =>
  f.hits >= BOSS_HP ? "won" : f.misses >= HEARTS || f.asked >= total ? "lost" : undefined;

const KEY = "inside-tech:world";

export function loadBeaten(): string[] {
  try {
    const v = JSON.parse(localStorage.getItem(KEY) ?? "[]");
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string" && ISLANDS.some((i) => i.lab === x)) : [];
  } catch {
    return [];
  }
}

/** Mark a boss beaten; true the first time, so the XP is counted once. */
export function markBeaten(lab: string): boolean {
  const all = loadBeaten();
  if (all.includes(lab)) return false;
  all.push(lab);
  try {
    localStorage.setItem(KEY, JSON.stringify(all));
  } catch {
    /* storage unavailable */
  }
  window.dispatchEvent(new Event("inside-tech:xp"));
  return true;
}
