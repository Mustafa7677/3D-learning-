export const JOURNEY_TOTAL = JOURNEY.reduce((t, s) => t + s.ms, 0);
export const XP_JOURNEY_ANSWER = 10;

const KEY = "inside-tech:journey";

/** Stop ids answered correctly (kept in this browser). */
export function loadJourney(): string[] {
  try {
    const v = JSON.parse(localStorage.getItem(KEY) ?? "[]");
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
  } catch {
    return [];
  }
}

export function saveJourneyAnswer(id: string): string[] {
  const done = loadJourney();
  if (!done.includes(id)) done.push(id);
  try {
    localStorage.setItem(KEY, JSON.stringify(done));
  } catch {
    /* storage unavailable */
  }
  window.dispatchEvent(new Event("inside-tech:xp"));
  return done;
}
