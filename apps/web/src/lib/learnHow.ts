const KEY = "inside-tech:learn-how";
export function loadSeen(): Record<string, boolean> {
  try {
    const v = JSON.parse(localStorage.getItem(KEY) ?? "{}");
    return v && typeof v === "object" ? Object.fromEntries(Object.entries(v).filter(([k, x]) => EPISODES.some((e) => e.id === k) && typeof x === "boolean")) as Record<string, boolean> : {};
  } catch {
    return {};
  }
}
export function saveSeen(v: Record<string, boolean>) {
  try {
    localStorage.setItem(KEY, JSON.stringify(v));
  } catch {
    /* storage unavailable */
  }
}
