/** Lowercase, keep Kazakh/Latin letters and digits, split on whitespace. */
export function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, " ")
    .split(/\s+/)
    .filter(Boolean);
}

export const SENTENCES: string[][] = CORPUS.map(words);
