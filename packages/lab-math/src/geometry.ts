import { withContent, type LessonDefinition, type SolutionFilm, type StepContent } from "@inside-tech/lesson-engine";
import { near } from "./linalg";
import { semiMinor, type ConicKind } from "./conic";
import type { MathLabAction, MathLabState } from "./plugin";

type L = LessonDefinition<MathLabState, MathLabAction>;
type S = MathLabState;

const ells = (s: S) => s.stats.ellipseSnaps;
const cuts = (s: S) => s.stats.conicSnaps;
const made = (s: S, kind: ConicKind) => cuts(s).some((x) => x.kind === kind);

/** Each frame's board is the previous board plus the new line(s). */
function build(frames: { stage: 0 | 1 | 2 | 3; add: string[]; mark?: string; say: string; scene?: Record<string, unknown> }[]): SolutionFilm["frames"] {
  const board: string[] = [];
  return frames.map((f) => {
    board.push(...f.add);
    return { stage: f.stage, board: [...board], mark: f.mark, say: f.say, scene: f.scene };
  });
}

