/** Each frame's board is the previous board plus the new line(s). */
function build(frames: { stage: 0 | 1 | 2 | 3; add: string[]; mark?: string; say: string; scene?: Record<string, unknown> }[]): SolutionFilm["frames"] {
  const board: string[] = [];
  return frames.map((f) => {
    board.push(...f.add);
    return { stage: f.stage, board: [...board], mark: f.mark, say: f.say, scene: f.scene };
  });
}

