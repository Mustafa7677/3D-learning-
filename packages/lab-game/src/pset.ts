/** The level spec of problem 2: enough content, all of it reachable, and not trivially short. */
export function levelMeetsSpec(level: string[]): boolean {
  const r = analyzeLevel(level);
  return r.coins >= 5 && r.enemies >= 2 && r.reachableCoins === r.coins && r.reachableEnemies === r.enemies && r.farthestCoin >= 12;
}

